import assert from 'node:assert/strict';
import { randomBytes } from 'node:crypto';
import { mkdir } from 'node:fs/promises';
import { chromium } from '@playwright/test';
import sharp from 'sharp';
const base = process.env.TEST_BASE_URL || 'http://127.0.0.1:3102';
assert.equal(new URL(base).port, '3102', 'Only run against the disposable sync verification server.');
const url = route => `${base}/api/spj?${new URLSearchParams({ route })}`;
const browser = await chromium.launch({ headless: true, args: ['--no-sandbox'] });
try {
  await mkdir('artifacts/sync', { recursive: true });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1024 } });
  const page = await context.newPage(); const errors = []; page.on('pageerror', e => errors.push(e.message));
  async function api(route, method = 'GET', data) { const response = await context.request.fetch(url(route), { method, data }); const body = await response.json(); assert.ok(response.ok(), `${route}: ${JSON.stringify(body)}`); return body; }
  await page.goto(base, { waitUntil: 'networkidle' });
  assert.equal((await api('state')).needsSetup, true);
  await page.getByPlaceholder('Nama lengkap Anda').fill('AKUN UJI SINKRON');
  await page.getByPlaceholder('username administrator').fill(`qa_sync_${Date.now()}`);
  await page.getByPlaceholder('Masukkan password').fill(randomBytes(14).toString('hex'));
  await page.getByRole('button', { name: 'Buat Akun & Lanjutkan' }).click();
  await page.getByRole('dialog').waitFor({ state: 'hidden' });
  let state = await api('state');
  console.log('PASS: fresh instance can create an administrator.');
  await api('school', 'PUT', { ...state.school, name: 'SD UJI SINKRON', government: 'PEMERINTAH KABUPATEN UJI', department: 'DINAS PENDIDIKAN UJI', address: 'JALAN UJI', district: 'KECAMATAN UJI', regency: 'KABUPATEN UJI', principal: 'KEPALA UJI', treasurer: 'BENDAHARA UJI', email: 'sekolah@uji.sch.id', website: 'uji.sch.id', npsn: '00000000' });
  await page.reload({ waitUntil: 'networkidle' });
  await page.getByRole('button', { name: 'Identitas Sekolah', exact: true }).click();
  await page.getByRole('button', { name: 'Kop & tanda tangan', exact: true }).click();
  await page.getByLabel('Baris instansi pemerintah').fill('PEMERINTAH KABUPATEN BARU');
  await page.getByLabel('Baris dinas / instansi').fill('DINAS PENDIDIKAN BARU');
  await page.getByLabel('Website sekolah').fill('sekolah-baru.sch.id');
  await page.getByLabel('Email sekolah').fill('baru@uji.sch.id');
  await page.getByRole('button', { name: 'Simpan Pengaturan', exact: true }).click();
  await page.getByText('Pengaturan sekolah berhasil disimpan', { exact: false }).waitFor();
  state = await api('state');
  assert.equal(state.school.government, 'PEMERINTAH KABUPATEN BARU');
  assert.equal(state.school.website, 'sekolah-baru.sch.id');
  const letterheadVisible = await page.locator('.letterhead-preview').textContent();
  assert.ok(letterheadVisible.includes('PEMERINTAH KABUPATEN BARU') && letterheadVisible.includes('baru@uji.sch.id'));
  console.log('PASS: two-logo letterhead fields save and render in the settings preview.');
  await api('school', 'PUT', { ...state.school, numberFormat: 'BNU{nomor}/SDN.SIDO 2/{bulan_romawi}/{tahun}' });
  const created = [];
  for (const [index, date] of ['2026-09-12', '2026-12-03', '2026-01-20'].entries()) {
    const transaction = await api('transactions', 'POST', { category: 'internet', title: `UJI NOMOR ${index + 1}`, date, amount: 10000 + index, data: { recipient: 'PENERIMA UJI', period: date.slice(0, 7) } });
    created.push(transaction);
  }
  assert.match(created[0].number, /^BNU\d{3}\/SDN\.SIDO 2\/IX\/2026$/);
  assert.match(created[1].number, /^BNU\d{3}\/SDN\.SIDO 2\/XII\/2026$/);
  assert.match(created[2].number, /^BNU\d{3}\/SDN\.SIDO 2\/I\/2026$/);
  assert.equal(new Set(created.map(t => t.number)).size, 3);
  assert.ok(created[0].number.startsWith('BNU001/'));
  console.log('PASS: receipt numbering uses BNU{no}, Roman month of the transaction date, and the year.');
  await page.reload({ waitUntil: 'networkidle' });
  await page.getByRole('button', { name: /Sinkronisasi & Lokal/ }).click();
  await page.getByRole('heading', { name: 'Sinkronisasi & Penyimpanan' }).waitFor();
  await page.screenshot({ path: 'artifacts/sync/sync-view-desktop.png', fullPage: true });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await page.getByRole('button', { name: 'Tarik Data', exact: true }).click();
  await page.getByText('Tarik data berhasil', { exact: false }).waitFor();
  let local = await page.evaluate(() => JSON.parse(localStorage.getItem('spj.snapshot.v1')));
  assert.equal(local.transactions.length, 3); assert.equal(local.source, 'server'); assert.equal(local.school.government, 'PEMERINTAH KABUPATEN BARU');
  console.log('PASS: Tarik Data stores the server snapshot on this device and refreshes the dashboard state.');
  await page.getByRole('button', { name: /Mode Lokal/ }).click();
  assert.equal(await page.evaluate(() => localStorage.getItem('spj.mode.v1')), 'local');
  await page.reload({ waitUntil: 'domcontentloaded' });
  await page.waitForFunction(() => document.body.innerText.includes('Mode lokal aktif'), null, { timeout: 20000 });
  console.log('PASS: local mode banner and device snapshot render immediately after reload.');
  await page.waitForFunction(() => JSON.parse(localStorage.getItem('spj.snapshot.v1') || '{}')?.transactions?.length === 3);
  console.log('PASS: local mode hydrates the interface from the device snapshot immediately after reload.');
  const offline = created[2];
  await page.evaluate(transaction => {
    const snapshot = JSON.parse(localStorage.getItem('spj.snapshot.v1'));
    snapshot.transactions = snapshot.transactions.map(item => item.id === transaction.id ? { ...item, title: 'JUDUL LOKAL BARU', updatedAt: new Date(Date.now() + 60000).toISOString() } : item);
    snapshot.transactions.push({ ...transaction, id: '00000000-0000-4000-8000-000000000099', number: '', title: 'TRANSAKSI DARI PERANGKAT', date: '2026-10-05', year: 2026, amount: 25000, data: { recipient: 'PENERIMA LOKAL', period: '2026-10' }, finalized: false, files: [], createdAt: new Date().toISOString(), updatedAt: new Date().toISOString() });
    snapshot.source = 'device';
    localStorage.setItem('spj.snapshot.v1', JSON.stringify(snapshot));
  }, offline);
  await page.getByRole('button', { name: 'Kirim Data Sekarang', exact: true }).click();
  await page.getByText('Kirim data selesai', { exact: false }).waitFor();
  state = await api('state');
  assert.equal(state.transactions.length, 4);
  assert.ok(state.transactions.some(t => t.title === 'JUDUL LOKAL BARU'));
  const pushed = state.transactions.find(t => t.title === 'TRANSAKSI DARI PERANGKAT');
  assert.ok(pushed && /^BNU\d{3}\/SDN\.SIDO 2\/X\/2026$/.test(pushed.number));
  const synced = await api('sync/pull');
  assert.equal(synced.transactions.length, 4);
  console.log('PASS: Kirim Data inserts device transactions, assigns the next BNU number, and updates newer edits.');
  const stale = await api('sync/push', 'POST', { transactions: [{ ...pushed, title: 'VERSI LAMA', updatedAt: new Date(Date.now() - 3600000).toISOString() }], applySchool: false });
  assert.equal(stale.result.updated, 0); assert.equal(stale.result.skipped, 1);
  assert.ok((await api('state')).transactions.find(t => t.id === pushed.id).title === 'TRANSAKSI DARI PERANGKAT');
  console.log('PASS: a stale device edit cannot overwrite a newer server transaction.');
  const image = await sharp({ create: { width: 40, height: 40, channels: 3, background: '#ccddee' } }).png().toBuffer();
  const form = new FormData(); form.set('kind', 'logo'); form.append('files', new Blob([image], { type: 'image/png' }), 'logo.png');
  const upload = await context.request.post(url('upload'), { multipart: { kind: 'logo', files: { name: 'logo.png', mimeType: 'image/png', buffer: image } } });
  assert.equal(upload.status(), 201);
  await page.getByRole('button', { name: 'Simpan ke Perangkat', exact: true }).click();
  await page.getByText('Salinan data tersimpan di perangkat', { exact: false }).waitFor();
  await page.setViewportSize({ width: 390, height: 844 }); await page.waitForTimeout(250);
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await page.screenshot({ path: 'artifacts/sync/sync-view-mobile.png', fullPage: true });
  console.log('PASS: Simpan ke Perangkat works and the sync screen is responsive on mobile.');
  assert.deepEqual(errors, []);
  console.log('ALL SYNC AND NUMBERING TESTS PASSED');
} finally { await browser.close(); }
