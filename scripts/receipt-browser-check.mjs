import assert from 'node:assert/strict';
import { randomBytes } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { chromium } from '@playwright/test';
import sharp from 'sharp';
import { PDFDocument } from 'pdf-lib';
import JSZip from 'jszip';
const base = process.env.TEST_BASE_URL || 'http://127.0.0.1:3101';
assert.ok(new URL(base).port === '3101', 'Run this test only against the isolated receipt verification server on port 3101.');
const url = route => `${base}/api/spj?${new URLSearchParams({ route })}`;
const browser = await chromium.launch({ headless: true, args: ['--no-sandbox'] });
try {
  await mkdir('artifacts/receipt-format', { recursive: true });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1050 } });
  const page = await context.newPage(); const errors = []; page.on('pageerror', e => errors.push(e.message));
  async function state() { const response = await context.request.get(url('state')); assert.ok(response.ok()); return response.json(); }
  async function api(route, method, data) { const response = await context.request.fetch(url(route), { method, data }); const body = await response.json(); assert.ok(response.ok(), `${route}: ${JSON.stringify(body)}`); return body; }
  await page.goto(base, { waitUntil: 'networkidle' });
  const initial = await state(); assert.equal(initial.needsSetup, true); assert.equal(initial.transactions.length, 0);
  await page.getByPlaceholder('Nama lengkap Anda').fill('AKUN UJI KUITANSI');
  await page.getByPlaceholder('username administrator').fill(`qa_receipt_${Date.now()}`);
  await page.getByPlaceholder('Masukkan password').fill(randomBytes(16).toString('hex'));
  await page.getByRole('button', { name: 'Buat Akun & Lanjutkan' }).click();
  await page.getByRole('dialog').waitFor({ state: 'hidden' });
  let saved = await state();
  await api('school', 'PUT', { ...saved.school, name: 'SEKOLAH UJI KUITANSI', npsn: '00000000', address: 'ALAMAT UJI SEMENTARA', principal: 'KEPALA SEKOLAH UJI', treasurer: 'BENDAHARA UJI', regency: 'TEMPAT UJI', principalNip: '00000000 000000 0 000' });
  await page.reload({ waitUntil: 'networkidle' });
  await page.getByRole('button', { name: 'Template Dokumen', exact: true }).click();
  await page.getByRole('heading', { name: 'Kuitansi rapi, sesuai kebutuhan.' }).waitFor();
  await page.locator('.receipt-live-preview').waitFor();
  assert.ok((await page.locator('.receipt-live-preview').textContent()).includes('[Nama penerima]'));
  await page.screenshot({ path: 'artifacts/receipt-format/designer-empty-desktop.png', fullPage: true });
  await page.getByRole('button', { name: /Teks saja.*Untuk kertas kuitansi bercetak/ }).click();
  assert.equal(await page.locator('.receipt-live-preview image').count(), 0);
  await page.getByRole('button', { name: /Putih bersih.*Susunan sama/ }).click();
  assert.ok((await page.locator('.receipt-live-preview').textContent()).includes('Telah terima dari'));
  await page.getByRole('button', { name: /Latar biru.*Motif kuitansi/ }).click();
  assert.equal(await page.locator('.receipt-live-preview image').count(), 1);
  console.log('PASS: blank preview uses placeholders, and all three style choices change the visible receipt.');
  await page.getByLabel('Lebar kuitansi (mm)').fill('200');
  await page.getByLabel('Tinggi kuitansi (mm)').fill('110');
  await page.getByLabel('Jabatan tanda tangan tengah').fill('Bendahara / Guru');
  const image = await sharp(await readFile('public/images/kuitansi-biru.svg')).resize({ width: 1800 }).png().toBuffer();
  await page.locator('#receipt-design-form input[type="file"]').setInputFiles({ name: 'latar-kuitansi-uji.png', mimeType: 'image/png', buffer: image });
  await page.getByRole('button', { name: 'Ganti gambar latar', exact: false }).waitFor();
  await page.getByLabel(/Latar sudah memuat label/).uncheck();
  await page.getByRole('button', { name: 'Simpan Format', exact: true }).click();
  await page.getByText('Format kuitansi berhasil disimpan.', { exact: false }).waitFor();
  saved = await state(); const backgroundId = saved.school.receiptBackgroundId;
  assert.ok(backgroundId); assert.equal(saved.school.receiptWidth, 200); assert.equal(saved.school.receiptHeight, 110); assert.equal(saved.school.receiptBackgroundHasLabels, false);
  await page.reload({ waitUntil: 'networkidle' });
  await page.getByRole('heading', { name: 'Kuitansi rapi, sesuai kebutuhan.' }).waitFor();
  assert.equal(await page.getByLabel('Lebar kuitansi (mm)').inputValue(), '200');
  assert.equal(await page.getByLabel('Tinggi kuitansi (mm)').inputValue(), '110');
  assert.equal(await page.getByLabel(/Latar sudah memuat label/).isChecked(), false);
  assert.ok((await page.locator('.receipt-live-preview image').first().getAttribute('href')).includes(backgroundId));
  const fileResponse = await context.request.get(url(`files/${backgroundId}`)); assert.equal(fileResponse.status(), 200);
  console.log('PASS: custom background and formatting persist in PostgreSQL after browser reload.');
  const transaction = await api('transactions', 'POST', { category: 'tahfidz', title: 'UJI FORMAT KUITANSI KEGIATAN', date: '2026-04-15', amount: 200000, data: { recipient: 'PENERIMA UJI KUITANSI', period: '2026-04' } });
  await page.reload({ waitUntil: 'networkidle' });
  await page.getByLabel('Transaksi untuk pratinjau kuitansi').selectOption(transaction.id);
  assert.ok((await page.locator('.receipt-live-preview').textContent()).includes(transaction.number));
  assert.ok((await page.locator('.receipt-live-preview').textContent()).includes('Dua ratus ribu rupiah'));
  await page.screenshot({ path: 'artifacts/receipt-format/designer-desktop.png', fullPage: true });
  const popupPromise = context.waitForEvent('page');
  await page.getByRole('button', { name: 'Lihat PDF / Cetak', exact: false }).click();
  const print = await popupPromise; await print.waitForLoadState('networkidle');
  await print.locator('iframe[title="Pratinjau PDF F4"]').waitFor();
  assert.ok(print.url().includes(`print/${transaction.id}`));
  await print.getByLabel('Format kuitansi').selectOption('text-only'); await print.waitForTimeout(700);
  await print.getByRole('button', { name: 'Download Word', exact: true }).waitFor({ state: 'visible' });
  await print.waitForFunction(() => !document.querySelector('.print-actions button')?.disabled);
  const downloadPromise = print.waitForEvent('download', { predicate: download => download.suggestedFilename().endsWith('.docx'), timeout: 45000 });
  await print.getByRole('button', { name: 'Download Word', exact: true }).click();
  const download = await downloadPromise; await download.saveAs('artifacts/receipt-format/browser-text-only.docx');
  const zip = await JSZip.loadAsync(await readFile('artifacts/receipt-format/browser-text-only.docx'));
  const xml = await zip.file('word/document.xml').async('string'); assert.ok(xml.includes('w:framePr')); assert.equal(xml.includes('behindDoc="1"'), false);
  const pdfResponse = await context.request.get(`${url(`export/${transaction.id}`)}&scope=receipt&format=pdf&receiptStyle=blue`); assert.equal(pdfResponse.status(), 200);
  const pdfBytes = await pdfResponse.body(); assert.equal((await PDFDocument.load(pdfBytes)).getPageCount(), 1); await writeFile('artifacts/receipt-format/browser-blue.pdf', pdfBytes);
  console.log('PASS: real transaction fills the receipt; preview and editable Word/PDF downloads work from the print workspace.');
  await print.close();
  await page.setViewportSize({ width: 390, height: 844 }); await page.waitForTimeout(250);
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await page.screenshot({ path: 'artifacts/receipt-format/designer-mobile.png', fullPage: true });
  console.log('PASS: receipt settings are usable on desktop and mobile with no page overflow.');
  const badSize = await context.request.put(url('school'), { data: { ...saved.school, receiptHeight: 1 } }); assert.equal(badSize.status(), 400);
  const backup = await api('backup', 'GET'); assert.equal(backup.school.receiptBackgroundId, backgroundId); assert.ok(backup.files.some(f => f.id === backgroundId && f.content));
  await api('school', 'PUT', { ...(await state()).school, receiptStyle: 'text-only', receiptWidth: 180 });
  await api('restore', 'POST', { backup, confirmation: 'PULIHKAN' });
  const restored = await state(); assert.equal(restored.school.receiptWidth, 200); assert.equal(restored.school.receiptBackgroundId, backgroundId); assert.equal(restored.school.receiptStyle, 'blue');
  console.log('PASS: backup/restore includes receipt format and background; invalid dimensions are rejected.');
  assert.deepEqual(errors, []); console.log('ALL RECEIPT BROWSER TESTS PASSED. Fixtures exist only in the disposable test database.');
} finally { await browser.close(); }
